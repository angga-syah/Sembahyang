/**
 * Dynamic color (Material You) SENGAJA dimatikan (default false) — keputusan eksplisit user,
 * bukan default Android yang dibiarkan begitu saja. Tanpa ini, warna app di Android 12+ ikut
 * wallpaper tiap user (bisa jadi apa saja), sehingga identitas visual teal/emas — termasuk yang
 * dipakai di icon launcher — tidak pernah benar-benar terlihat konsisten di dalam app itu
 * sendiri. Palet teal/emas di bawah sekarang jadi SATU-SATUNYA sumber warna, bukan cadangan
 * untuk HP lama saja — berlaku sama di semua versi Android.
 */
@Composable
fun SholatTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = SholatTypography,
        content = content,
    )
}
